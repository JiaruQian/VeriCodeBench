#!/usr/bin/env python3
"""Validate the maintained manual ground-truth spec file.

The benchmark's ground truth is a curated JSON file. It intentionally combines
requirement-derived ACSL targets and reference-spec-derived ACSL targets into one
manual target set, so it should not be regenerated by blindly extracting every
contract clause from the reference C files.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List


PROJECT_ROOT = Path(__file__).resolve().parents[1]
REQ_FILE = PROJECT_ROOT / "benchmarks/frama-c-problems/requirements/requirements_100.json"
GROUND_TRUTH_SPEC_FILE = (
    PROJECT_ROOT
    / "benchmarks/frama-c-problems/requirements/requirements_100_ground_truth_specs.json"
)


def _load_json_array(path: Path) -> List[Dict[str, Any]]:
    data = json.loads(path.read_text())
    if not isinstance(data, list):
        raise ValueError(f"{path} must contain a JSON array")
    return data


def main() -> None:
    requirements = _load_json_array(REQ_FILE)
    ground_truth = _load_json_array(GROUND_TRUTH_SPEC_FILE)

    req_ids = [int(row["id"]) for row in requirements]
    gt_ids = [int(row["id"]) for row in ground_truth]
    if req_ids != gt_ids:
        raise SystemExit(
            "ground-truth spec ids do not match requirements_100.json order: "
            f"requirements={req_ids} ground_truth={gt_ids}"
        )

    total_clauses = 0
    for row in ground_truth:
        clauses = row.get("ground_truth_clauses")
        if not isinstance(clauses, list):
            raise SystemExit(f"id={row.get('id')} missing ground_truth_clauses list")
        for clause in clauses:
            ctype = str(clause.get("type", "")).strip()
            expr = str(clause.get("expr", "")).strip()
            if ctype not in {"requires", "ensures", "assigns"}:
                raise SystemExit(f"id={row.get('id')} invalid clause type: {ctype!r}")
            if not expr:
                raise SystemExit(f"id={row.get('id')} has empty ground-truth expr")
        total_clauses += len(clauses)

    # Normalize formatting without changing the curated target set.
    GROUND_TRUTH_SPEC_FILE.write_text(json.dumps(ground_truth, ensure_ascii=False, indent=2))
    print(
        f"[OK] validated {GROUND_TRUTH_SPEC_FILE} "
        f"tasks={len(ground_truth)} clauses={total_clauses}"
    )


if __name__ == "__main__":
    main()
